const mongoose = require('mongoose');

const attendanceSchema = new mongoose.Schema(
  {
    // Stored as YYYY-MM-DD string for reliable daily uniqueness across timezones
    date: {
      type: String,
      required: true,
      unique: true,
      match: /^\d{4}-\d{2}-\d{2}$/,
    },
    status: {
      type: String,
      enum: ['present', 'CL', 'SL', 'LOP', 'absent', 'weekend'],
      required: true,
    },
    checkInTime: {
      type: String, // stored as HH:MM
      default: null,
    },
    note: {
      type: String,
      default: '',
      maxlength: 1000,
    },
    // Was this record auto-generated by the missed check-in rule?
    autoMarked: {
      type: Boolean,
      default: false,
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model('Attendance', attendanceSchema);

